"""Write the "every file" guide into LEARN.md (between <!-- FILES:START --> and <!-- FILES:END -->): each source
file, its size and what it does, taken from the docstring at the top of the file (Python) or its first comment
(JavaScript). Run it after adding or removing files: `make files-guide`. Never edit that part by hand.
"""
from __future__ import annotations

import ast
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
LEARN = ROOT / "LEARN.md"
START, END = "<!-- FILES:START -->", "<!-- FILES:END -->"
GROUPS = [  # (folder, heading)
    ("jarvis", "Start-up (how KURAMA is launched)"),
    ("jarvis/api", "The web server the window talks to"),
    ("jarvis/api/routes", "Its addresses (one file per area)"),
    ("jarvis/core", "The brain and the services (most of the logic)"),
    ("jarvis/core/intents", "Instant commands, by area"),
    ("jarvis/tools/core", "The few general tools the AI sees"),
    ("jarvis/tools/general", "The real tools (one file each)"),
    ("jarvis/tools/interactive", "More real tools (code, files)"),
    ("jarvis/memories", "Kinds of memory (one file each)"),
    ("jarvis/agents", "Agents"),
    ("jarvis/agents/coding", "The coding agent"),
    ("jarvis/workers", "Background helpers"),
    ("frontend", "The window (what you see)"),
    ("scripts", "Scripts (start, stop, the desktop window, reports)"),
]


def first_sentence(text: str, limit: int = 170) -> str:
    t = " ".join((text or "").split())
    t = re.sub(r"^[\w./-]+\.py:\s*|^`?[\w.]+`?:\s+", "", t)  # "find_files: find files..." -> "find files..."
    m = re.match(r"(.+?[.!?])(?:\s|$)", t)
    s = (m.group(1) if m else t).strip()
    return (s[:limit - 1] + "…") if len(s) > limit else s


def describe(p: Path) -> str:
    src = p.read_text(encoding="utf-8", errors="replace")
    if p.suffix == ".py":
        try:
            return first_sentence(ast.get_docstring(ast.parse(src)) or "")
        except SyntaxError:
            return ""
    lines = []
    for ln in src.splitlines()[:12]:
        s = ln.strip()
        if s.startswith("//"):
            lines.append(s.lstrip("/ "))
        elif lines:
            break
    return first_sentence(" ".join(lines))


def build() -> str:
    out = [START, "", "_Generated by `scripts/file_guide.py` from each file's own description; run `make files-guide` "
           "after adding a file._", ""]
    for folder, heading in GROUPS:
        d = ROOT / folder
        pats = ("*.py",) if folder != "frontend" else ("*.js",)
        files = sorted(f for pat in pats for f in d.glob(pat) if f.name != "__init__.py" or describe(f))
        if not files:
            continue
        out += [f"#### `{folder}/`: {heading}", "", "| File | Lines | What it does |", "|---|---|---|"]
        for f in files:
            n = sum(1 for _ in f.open(encoding="utf-8", errors="replace"))
            out.append(f"| `{f.name}` | {n} | {describe(f).replace('|', '/') or '—'} |")
        out.append("")
    out.append(END)
    return "\n".join(out)


def main() -> None:
    text = LEARN.read_text(encoding="utf-8")
    if START not in text or END not in text:
        raise SystemExit(f"LEARN.md has no {START} ... {END} markers")
    a, b = text.index(START), text.index(END) + len(END)
    LEARN.write_text(text[:a] + build() + text[b:], encoding="utf-8")
    print("LEARN.md: file guide updated")


if __name__ == "__main__":
    main()
